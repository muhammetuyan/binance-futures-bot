export function translate(value: string, language: Language): string {
  if (language === 'tr') return value;
  const paperStatus = value.match(/^(\d+(?:\.\d+)?) USDT paper hesapla (\d+) likit parite her (\d+) dakikada 15dk\+1s taranıyor$/);
  if (paperStatus) return `Paper account (${paperStatus[1]} USDT): scanning ${paperStatus[2]} liquid symbols every ${paperStatus[3]} minutes with 15m + 1h candles.`;
  let result = phrases[value] ?? value;
  for (const [from, to] of fragments) result = result.replaceAll(from, to);
  if (result.startsWith('Binance bağlantı hatası:')) return 'Binance market data connection error. Check your internet, firewall, or proxy settings.';
  if (result === 'Binance bağlantısı kurulamadı. API izinlerini ve IP kısıtını kontrol edin.') return 'Could not connect to Binance. Check API permissions and IP restrictions.';
  return result;
}

